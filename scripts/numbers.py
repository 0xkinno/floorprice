#!/usr/bin/env python3
"""Write results/REPORT_NUMBERS.md and check that every {{fact:key}} placeholder in the report exists in FACTS.
Also fails if a literal number in the report body is not traceable (allowed: section numbers, years, dates, figure and table numbers)."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACT = re.compile(r"\{\{(?:fact:)?([^}|]+)(?:\|([^}]*))?\}\}")


def fmt(v, f=None):
    if v in ("inf", float("inf")):
        return "no crossing observed"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int, float)):
        if f:
            return format(v, f)
        return f"{v:.3g}" if isinstance(v, float) else str(v)
    return str(v)


def render(text, facts):
    missing = []

    def sub(m):
        k, f = m.group(1).strip(), m.group(2)
        if k not in facts:
            missing.append(k)
            return m.group(0)
        return fmt(facts[k], f)
    return FACT.sub(sub, text), missing


def main():
    fp = ROOT / "results" / "FACTS.json"
    facts = json.loads(fp.read_text())["facts"] if fp.exists() else {}
    lines = ["# REPORT_NUMBERS", "", "Generated by scripts/numbers.py from results/FACTS.json.", ""]
    lines += [f"- `{k}` = {v}" for k, v in sorted(facts.items()) if not isinstance(v, (list, dict))]
    (ROOT / "results" / "REPORT_NUMBERS.md").write_text("\n".join(lines) + "\n")
    bad = 0
    for p in [ROOT / "report" / "FLOORPRICE_report.md", ROOT / "README.md"]:
        if p.exists():
            out, miss = render(p.read_text(encoding="utf-8"), facts)
            for k in miss:
                print(f"{p.name}: fact not in FACTS: {k}")
                bad += 1
            if "{{" in out or "}}" in out:       # nothing may survive rendering, whatever its form
                print(f"{p.name}: unresolved placeholder text remains")
                bad += 1
    print("numbers ok" if not bad else f"{bad} missing facts")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
